"""A dedicated hand detector against the same human labels as the VLM monitor (post hoc, offline replay).

The frozen 2158-frame pool was also processed, before any human label existed, by Apple Vision's
built-in hand-pose request (VNDetectHumanHandPoseRequest, OS-managed weights; OS build and request
revision recorded in its metadata). Here a frame counts as a detector hand report when the request
returned at least one hand observation. Its reports and FastVLM's replay verdicts are compared with
the merged first-annotator labels and, separately, with the second annotator's labels on the frozen
426-frame sample; uncertain human labels are excluded from the counts. Processing times are the
per-frame elapsed times recorded by each offline replay on all 2158 frames, on the same laptop; they
are not live pipeline latencies. Detector outputs are model outputs and are never used as labels.
"""
import collections, json, statistics as st, hashlib
from pathlib import Path
HERE = Path(__file__).resolve().parent

def _find(rel):
    for base in (HERE.parent.parent, HERE.parent / "paper-data"):
        if (base / rel).exists():
            return base / rel
    raise FileNotFoundError(rel)

AV_PATH = _find("semantic_auto_audit/apple_vision_all_20260924T193552_399674Z/hand_pose_all.jsonl")
J_PATH = _find("semantic_human_review/merged_2026-09-25_v1/joined_records.json")
S_PATH = _find("semantic_human_review/second_rater_426_v1/human_review_426_second_rater.json")
M_PATH = _find("semantic_auto_audit/run_20260924_203640/monitor.jsonl")
av_rows = [json.loads(l) for l in AV_PATH.read_text().splitlines() if l.strip()]
meta = next(r for r in av_rows if r.get("record_type") == "metadata")
AV = {r["id"]: r for r in av_rows if r.get("record_type") == "frame"}
assert len(AV) == 2158 and all(not r["errors"] for r in AV.values())
first = json.loads(J_PATH.read_text())["records"]
second = {r["id"]: r for r in json.loads(S_PATH.read_text())["labels"]}
mon = {m["id"]: m for m in (json.loads(l) for l in M_PATH.read_text().splitlines() if l.strip())}
assert len(first) == 426 and set(second) == {r["case_id"] for r in first}


def counts(label_of, cover_of):
    out = {"FastVLM": collections.Counter(), "Apple Vision": collections.Counter()}
    for r in first:
        lab = label_of(r)
        if lab == "uncertain":
            continue
        fv = r["automatic"]["monitor"]["prediction"] == "HUMAN"
        av = AV[r["frame"]["original_id"]]["num_detections"] > 0
        for name, hit in (("FastVLM", fv), ("Apple Vision", av)):
            c = out[name]
            if lab == "hand":
                c["hand"] += 1; c["hand_reported"] += hit
                cov = cover_of(r) or "unspecified"
                c[f"hand_{cov}"] += 1; c[f"hand_{cov}_reported"] += hit
            else:
                c["no_hand"] += 1; c["no_hand_reported"] += hit
    return {k: dict(v) for k, v in out.items()}


ref_first = counts(lambda r: r["human"]["label"], lambda r: r["human"].get("cover"))
ref_second = counts(lambda r: second[r["case_id"]]["label"], lambda r: second[r["case_id"]].get("cover"))
both = [r for r in first if r["human"]["label"] == "hand"
        and AV[r["frame"]["original_id"]]["num_detections"] == 0 and r["automatic"]["monitor"]["prediction"] == "HUMAN"]
av_t = [r["elapsed_s"] for r in AV.values()]
fv_t = [m["inference_s"] for m in mon.values() if m.get("inference_s") is not None]
q = lambda xs, f: sorted(xs)[int(f * (len(xs) - 1))]
out = {"note": __doc__, "detector_metadata": {k: meta[k] for k in ("detector", "os_version", "request_revision", "weight_provenance_limit")},
       "reference_first_annotator": ref_first, "reference_second_annotator": ref_second,
       "hand_frames_missed_by_detector_but_flagged_by_FastVLM": len(both),
       "processing_time_ms": {"Apple Vision": {"frames": len(av_t), "median": 1000 * st.median(av_t), "p95": 1000 * q(av_t, .95)},
                              "FastVLM": {"frames": len(fv_t), "median": 1000 * st.median(fv_t), "p95": 1000 * q(fv_t, .95)}},
       "pool_reports": {"Apple Vision": sum(r["num_detections"] > 0 for r in AV.values()),
                        "FastVLM": sum(m["prediction"] == "HUMAN" for m in mon.values()), "frames": len(AV)},
       "sources_sha256": {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in (AV_PATH, J_PATH, S_PATH, M_PATH)}}
(HERE / "hand_detector_comparison_results.json").write_text(json.dumps(out, indent=2) + "\n")

lines = []
for name in ("FastVLM", "Apple Vision"):
    a, b = ref_first[name], ref_second[name]; t = out["processing_time_ms"][name]
    lines.append(f"{name} & {a['hand_reported']}/{a['hand']} & {a['hand_bare_reported']}/{a['hand_bare']} & {a['hand_glove_reported']}/{a['hand_glove']} & {a['no_hand_reported']}/{a['no_hand']} & {b['hand_reported']}/{b['hand']} & {b['no_hand_reported']}/{b['no_hand']} & {t['median']:.1f}\\\\")
tex = [r"% Generated by hand_detector_comparison.py; offline replay on the frozen frames, human labels as reference.",
       r"\begin{table}[H]\centering\small",
       r"\caption{FastVLM replay and a dedicated hand detector (Apple Vision hand-pose request) on the frozen 426-frame sample, against the merged first-annotator labels and, separately, the second annotator's labels; uncertain labels are excluded. Entries are frames with a hand report over frames in the class; counts are raw values in an enriched sample, not population rates. Time: median per-frame processing time of each offline replay over all 2158 frames on the same laptop, not a live pipeline latency.}\label{tab:hand-detector}",
       r"\begin{tabularx}{\linewidth}{>{\raggedright\arraybackslash}Xrrrrrrr}",
       r"\toprule & \multicolumn{4}{c}{First annotator (reference)} & \multicolumn{2}{c}{Second annotator} & \\ \cmidrule(lr){2-5}\cmidrule(lr){6-7}",
       r"Monitor & Hand & Bare & Gloved & No hand & Hand & No hand & Time (ms)\\ \midrule", *lines,
       r"\bottomrule", r"\end{tabularx}", r"\end{table}"]
(HERE / "hand_detector_comparison_table.tex").write_text("\n".join(tex) + "\n")
print(json.dumps({k: out[k] for k in ("reference_first_annotator", "reference_second_annotator", "hand_frames_missed_by_detector_but_flagged_by_FastVLM", "processing_time_ms", "pool_reports")}, indent=1))
