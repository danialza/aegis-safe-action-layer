"""L + P/2 sweep account checked run by run on all 92 eligible transports (post hoc, no fitted parameter).

age_reuse_model.py compares the sweep value L + P/2 with the observed mean moving-decision age for the
24 primary runs. Here the same comparison is made for every eligible transport: the primary campaign,
the slow-update pilot, the exploratory campaign and the initial capture-proxy pilot. P is the median
start-to-start interval and L the mean capture-proxy-to-inference-end latency of the evidence bundles
consumed by the run's carry decisions, as in duty_cycle.analyse_run; the observed value is the mean
logged age over decisions whose mode is not 'stop', as in the run-level audit. A policy that moves
regardless of evidence age is expected to lie near L + P/2; the age-aware rule departs from it when
its score hold refuses motion on old evidence, which happens only when P + L exceeds the hold onset.
The sets are summarized separately and are not pooled into a matched comparison.
"""
import glob, json, os, statistics as st, hashlib
from pathlib import Path
HERE = Path(__file__).resolve().parent

def _find(rel):
    for base in (HERE.parent.parent, HERE.parents[1] / "10_hardware_manuscript_2026-09-24"):
        if (base / rel).exists():
            return base / rel
    raise FileNotFoundError(rel)

SETS = (("timed_margin_compare", "Primary"), ("timed_compare_slow", "Slow-update pilot"),
        ("timed_compare", "Exploratory"), ("aegis_time", "Initial pilot"))


def method_of(d):
    if d["variant"].startswith("AEGIS"):
        return "AEGIS"
    return "Trust32" if abs(d["clasp_params"]["epi"] - 0.032) < 1e-9 else "Trust12"


def analyse(f):
    d = json.load(open(f))
    bundles = {}
    for e in d["log"]:
        if e.get("ev_t_infer_start") is not None:
            bundles[e.get("ev_seq", e["ev_t_infer_start"])] = (e["ev_t_infer_start"], e["ev_t_infer_end"], e["ev_t_capture"])
    starts = sorted(v[0] for v in bundles.values())
    moving = [e["age_used"] for e in d["log"] if e["mode"] != "stop"]
    if len(starts) < 3 or not moving:
        return None
    P = st.median(b - a for a, b in zip(starts, starts[1:]))
    L = st.mean(v[1] - v[2] for v in bundles.values())
    return {"run": os.path.basename(f)[:-5], "method": method_of(d),
            "cadence": "slow" if d.get("vlm_min_period_s") else "normal",
            "P_ms": 1000 * P, "L_ms": 1000 * L, "L_plus_half_P_ms": 1000 * (L + P / 2),
            "observed_mean_moving_age_ms": 1000 * st.mean(moving), "moving_decisions": len(moving),
            "residual_ms": 1000 * (st.mean(moving) - L - P / 2),
            "source_sha256": hashlib.sha256(Path(f).read_bytes()).hexdigest()}


def summary(rs):
    res = [r["residual_ms"] for r in rs]
    return {"runs": len(rs), "L_plus_half_P_ms_mean": st.mean(r["L_plus_half_P_ms"] for r in rs),
            "observed_ms_mean": st.mean(r["observed_mean_moving_age_ms"] for r in rs),
            "residual_ms_mean": st.mean(res), "residual_ms_sd": st.pstdev(res) if len(res) > 1 else 0.0,
            "residual_ms_min": min(res), "residual_ms_max": max(res), "max_abs_residual_ms": max(map(abs, res))}


runs, skipped = [], []
for folder, label in SETS:
    for f in sorted(glob.glob(str(_find(f"data/{folder}/logs") / "*.json"))):
        r = analyse(f)
        if r is None:
            skipped.append(os.path.basename(f)); continue
        r["set"] = label; runs.append(r)
rows = {}
for r in runs:
    rows.setdefault((r["set"], r["method"], r["cadence"]), []).append(r)
age_independent = [r for r in runs if r["method"] != "AEGIS" or r["cadence"] == "normal"]
slow_aegis = [r for r in runs if r["method"] == "AEGIS" and r["cadence"] == "slow"]
out = {"note": __doc__, "runs_analysed": len(runs), "runs_skipped": skipped,
       "rows": {" | ".join(k): summary(v) for k, v in rows.items()},
       "fixed_buffer_and_normal_cadence_AEGIS": summary(age_independent),
       "slow_cadence_AEGIS": summary(slow_aegis),
       "share_age_independent_within_30_ms": sum(abs(r["residual_ms"]) <= 30 for r in age_independent) / len(age_independent),
       "runs": runs}
(HERE / "pipeline_age_all_runs_results.json").write_text(json.dumps(out, indent=2) + "\n")

fmt = lambda x: f"{x:.1f}".replace("-", "$-$")
lines = []
for (s, m, c), v in rows.items():
    q = summary(v)
    lines.append(f"{s} & {m} & {c.capitalize()} & {q['runs']} & {q['L_plus_half_P_ms_mean']:.1f} & {q['observed_ms_mean']:.1f} & {fmt(q['residual_ms_mean'])} & {fmt(q['residual_ms_min'])} to {fmt(q['residual_ms_max'])}\\\\")
a, b = out["fixed_buffer_and_normal_cadence_AEGIS"], out["slow_cadence_AEGIS"]
tex = [r"% Generated by pipeline_age_all_runs.py; run-level values, no fitted parameter.",
       r"\begin{table}[H]\centering\small",
       r"\caption{Sweep value $L+P/2$ and observed mean moving-decision age on all eligible transports, in ms. $P$ and $L$ are each run's update period and capture-proxy-to-inference-end latency; residual = observed $-$ $(L+P/2)$, summarized as the mean and range of run-level residuals. The sets are not pooled into a matched comparison. The exploratory and initial-pilot runs ran at normal cadence; Trust12 denotes the 12 mm fixed buffer in every set. No parameter is fitted.}\label{tab:age-sweep-all}",
       r"\begin{tabularx}{\linewidth}{>{\raggedright\arraybackslash}Xllrrrrr}",
       r"\toprule Set & Method & Cadence & Runs & $L+P/2$ & Observed & Residual & Range\\ \midrule", *lines,
       r"\midrule",
       f"\\multicolumn{{3}}{{l}}{{Fixed buffers, and AEGIS at normal cadence}} & {a['runs']} & {a['L_plus_half_P_ms_mean']:.1f} & {a['observed_ms_mean']:.1f} & {fmt(a['residual_ms_mean'])} & {fmt(a['residual_ms_min'])} to {fmt(a['residual_ms_max'])}\\\\",
       f"\\multicolumn{{3}}{{l}}{{AEGIS at slow cadence}} & {b['runs']} & {b['L_plus_half_P_ms_mean']:.1f} & {b['observed_ms_mean']:.1f} & {fmt(b['residual_ms_mean'])} & {fmt(b['residual_ms_min'])} to {fmt(b['residual_ms_max'])}\\\\",
       r"\bottomrule", r"\end{tabularx}", r"\end{table}"]
(HERE / "pipeline_age_all_runs_table.tex").write_text("\n".join(tex) + "\n")
print(json.dumps({k: out[k] for k in ("runs_analysed", "runs_skipped", "fixed_buffer_and_normal_cadence_AEGIS", "slow_cadence_AEGIS", "share_age_independent_within_30_ms")}, indent=1))
