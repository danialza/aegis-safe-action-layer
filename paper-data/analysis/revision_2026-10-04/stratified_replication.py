"""Stratified exact permutation test: primary campaign and slow-update pilot as two strata (post hoc).

The eight-run slow-update pilot repeated the slow-cadence AEGIS-versus-Trust12 comparison in a separate
block before the primary campaign. Runs are not pooled: labels are permuted only within each stratum
(70 x 70 = 4900 joint reassignments), and the statistic is the sum over strata of the AEGIS-minus-Trust12
difference of run means, so each stratum keeps its own level. The two-sided p is the share of joint
reassignments whose absolute statistic is at least the observed one. Holm adjustment is over the four
outcomes. Only this contrast has a replicate stratum: the pilot has no Trust32 runs and no normal cadence.
The stratified test was chosen after the primary analysis and is reported as a secondary analysis.
"""
import itertools, json, statistics as st, hashlib
from pathlib import Path
HERE = Path(__file__).resolve().parent

def _find(rel):
    for base in (HERE.parent.parent, HERE.parents[1] / "10_hardware_manuscript_2026-09-24"):
        if (base / rel).exists():
            return base / rel
    raise FileNotFoundError(rel)

SRC = _find("analysis/exploratory_patterns_2026-10-02/pattern_results.json")
METRICS = {"Mean moving age (ms)": "mean_moving_age_ms", "Separation (mm)": "minimum_command_estimated_separation_mm",
           "Carry-to-delivery (s)": "carry_to_delivery_s", "Age $>0.6$ s (\\%)": "moving_old_evidence_percent"}
runs = json.loads(SRC.read_text())["runs"]
STRATA = (("Primary", "timed_margin_compare"), ("Pilot", "timed_compare_slow"))


def values(camp, method, key):
    return [r[key] for r in runs if r["campaign"] == camp and r["method"] == method and r["rate"] == "slow"]


def null_differences(a, b):
    pool = a + b; n = len(a); out = []
    for idx in itertools.combinations(range(len(pool)), n):
        out.append(st.mean(pool[i] for i in idx) - st.mean(pool[i] for i in range(len(pool)) if i not in idx))
    return out


res = []
for label, key in METRICS.items():
    strata = [(values(c, "AEGIS", key), values(c, "Trust12", key)) for _, c in STRATA]
    assert all(len(a) == 4 and len(b) == 4 for a, b in strata)
    obs = sum(st.mean(a) - st.mean(b) for a, b in strata)
    nulls = [null_differences(a, b) for a, b in strata]
    hits = tot = 0
    for combo in itertools.product(*nulls):
        tot += 1; hits += abs(sum(combo)) >= abs(obs) - 1e-9
    per = []
    for (name, _), (a, b), nd in zip(STRATA, strata, nulls):
        d = st.mean(a) - st.mean(b)
        per.append({"stratum": name, "AEGIS_minus_Trust12": d, "p": sum(abs(x) >= abs(d) - 1e-9 for x in nd) / len(nd),
                    "complete_separation": max(a) < min(b) or min(a) > max(b)})
    res.append({"outcome": label, "key": key, "mean_of_stratum_differences": obs / len(strata),
                "stratified_p": hits / tot, "reassignments": tot, "strata": per})
order = sorted(range(len(res)), key=lambda i: res[i]["stratified_p"])
running = 0.0
for rank, i in enumerate(order):
    running = max(running, min(1.0, (len(res) - rank) * res[i]["stratified_p"]))
    res[i]["holm_p"] = running
out = {"note": __doc__, "source": SRC.name, "source_sha256": hashlib.sha256(SRC.read_bytes()).hexdigest(),
       "minimum_attainable_p": 2 / 4900, "results": res}
(HERE / "stratified_replication_results.json").write_text(json.dumps(out, indent=2) + "\n")

fp = lambda p: f"{p:.4f}" if p < 0.01 else f"{p:.3f}"
fd = lambda x: f"{x:+.1f}".replace("+-", "$-$").replace("-", "$-$").replace("+", "")
lines = [f"{r['outcome']} & {fd(r['strata'][0]['AEGIS_minus_Trust12'])} & {fd(r['strata'][1]['AEGIS_minus_Trust12'])} & {fp(r['strata'][1]['p'])} & {fp(r['stratified_p'])} & {fp(r['holm_p'])}\\\\" for r in res]
tex = [r"% Generated by stratified_replication.py; post hoc secondary analysis.",
       r"\begin{table}[H]\centering\small",
       r"\caption{Slow-cadence AEGIS minus Trust12 in the primary campaign and in the separate slow-update pilot, with a stratified exact permutation test that permutes labels only within each set (4900 joint reassignments; smallest attainable two-sided $p=2/4900\approx0.0004$). The primary-set $p$ is 0.029 for every outcome (Table~\ref{tab:exact-full}). Holm adjustment is over the four outcomes. The test was chosen after the primary analysis; the pilot was recorded in an earlier block and has no Trust32 or normal-cadence runs.}\label{tab:stratified}",
       r"\begin{tabularx}{\linewidth}{>{\raggedright\arraybackslash}Xrrrrr}",
       r"\toprule Outcome & Primary & Pilot & Pilot $p$ & Stratified $p$ & Holm $p$\\ \midrule", *lines,
       r"\bottomrule", r"\end{tabularx}", r"\end{table}"]
(HERE / "stratified_replication_table.tex").write_text("\n".join(tex) + "\n")
for r in res:
    print(r["outcome"], round(r["mean_of_stratum_differences"], 2), r["stratified_p"], r["holm_p"], [(s["stratum"], round(s["AEGIS_minus_Trust12"], 2), round(s["p"], 4), s["complete_separation"]) for s in r["strata"]])
